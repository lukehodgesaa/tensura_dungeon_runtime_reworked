package com.mineclawd.tensuradungeon.command;

import com.mojang.brigadier.arguments.IntegerArgumentType;
import com.mojang.brigadier.builder.LiteralArgumentBuilder;
import net.minecraft.commands.CommandSourceStack;
import net.minecraft.commands.Commands;
import net.minecraft.commands.arguments.EntityArgument;

final class RunCommandRegistrar {
    private RunCommandRegistrar() {
    }

    static void register(
        LiteralArgumentBuilder<CommandSourceStack> root,
        LiteralArgumentBuilder<CommandSourceStack> generatedFloor
    ) {
        root.then(Commands.literal("floor")
            .then(Commands.literal("progress").executes(RunCommandHandlers::debugFloorProgress))
            .then(Commands.literal("debug").executes(RunCommandHandlers::debugFloorProgress))
            .then(Commands.literal("start")
                .then(Commands.argument("floor", IntegerArgumentType.integer(1))
                    .executes(RunCommandHandlers::startFloorRun)))
            .then(Commands.literal("enter")
                .then(Commands.argument("floor", IntegerArgumentType.integer(1))
                    .executes(GeneratedLinearConnectorPlacementCommands::enterGeneratedFloor)
                    .then(Commands.argument("player", EntityArgument.player())
                        .executes(GeneratedLinearConnectorPlacementCommands::enterGeneratedFloorForPlayer))))
            .then(Commands.literal("enterselected")
                .executes(GeneratedLinearConnectorPlacementCommands::enterSelectedGeneratedFloor)
                .then(Commands.argument("player", EntityArgument.player())
                    .executes(GeneratedLinearConnectorPlacementCommands::enterSelectedGeneratedFloorForPlayer)))
            .then(Commands.literal("preset")
                .then(Commands.literal("scan").executes(RunCommandHandlers::scanPresetFloor))
                .then(Commands.literal("chainscan")
                    .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                        .executes(RunCommandHandlers::chainScanPresetFloor))
                    .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                        .then(Commands.argument("stepRadius", IntegerArgumentType.integer(1))
                            .executes(RunCommandHandlers::chainScanPresetFloor))))
                .then(Commands.literal("status").executes(RunCommandHandlers::presetFloorStatus))
                .then(Commands.literal("start")
                    .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                        .executes(RunCommandHandlers::startPresetFloorRun))
                    .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                        .then(Commands.literal("chained")
                            .executes(RunCommandHandlers::startChainedPresetFloorRun))
                        .then(Commands.literal("chained")
                            .then(Commands.argument("stepRadius", IntegerArgumentType.integer(1))
                                .executes(RunCommandHandlers::startChainedPresetFloorRun))))))
            .then(Commands.literal("linear")
                .then(Commands.literal("scan").executes(RunCommandHandlers::scanPresetFloor))
                .then(Commands.literal("chainscan")
                    .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                        .executes(RunCommandHandlers::chainScanPresetFloor))
                    .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                        .then(Commands.argument("stepRadius", IntegerArgumentType.integer(1))
                            .executes(RunCommandHandlers::chainScanPresetFloor))))
                .then(Commands.literal("claimscan")
                    .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                        .executes(RunCommandHandlers::postPlacementClaimLinearScan))
                    .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                        .then(Commands.argument("stepRadius", IntegerArgumentType.integer(1))
                            .executes(RunCommandHandlers::postPlacementClaimLinearScan))))
                .then(Commands.literal("status").executes(RunCommandHandlers::presetFloorStatus))
                .then(Commands.literal("start")
                    .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                        .executes(RunCommandHandlers::startPresetFloorRun))
                    .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                        .then(Commands.literal("chained")
                            .executes(RunCommandHandlers::startChainedPresetFloorRun))
                        .then(Commands.literal("chained")
                            .then(Commands.argument("stepRadius", IntegerArgumentType.integer(1))
                                .executes(RunCommandHandlers::startChainedPresetFloorRun))))))
            .then(Commands.literal("claimstart")
                .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                    .executes(RunCommandHandlers::startPostPlacementClaimLinearRun))
                .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                    .then(Commands.argument("stepRadius", IntegerArgumentType.integer(1))
                        .executes(RunCommandHandlers::startPostPlacementClaimLinearRun))))
            .then(generatedFloor)
            .then(Commands.literal("clearprogress").executes(RunCommandHandlers::clearFloorProgress)));

        root.then(Commands.literal("run")
            .then(Commands.literal("start").executes(RunCommandHandlers::startRun))
            .then(Commands.literal("enterselected")
                .executes(GeneratedLinearConnectorPlacementCommands::enterSelectedGeneratedFloor)
                .then(Commands.argument("player", EntityArgument.player())
                    .executes(GeneratedLinearConnectorPlacementCommands::enterSelectedGeneratedFloorForPlayer)))
            .then(Commands.literal("debug").executes(RunCommandHandlers::debugRun))
            .then(Commands.literal("exitdebug").executes(RunCommandHandlers::debugRunExitPortal))
            .then(Commands.literal("modifierdebug").executes(RunCommandHandlers::debugRunModifiers))
            .then(Commands.literal("modifier")
                .then(Commands.literal("armored")
                    .executes(context -> RunCommandHandlers.setRunModifier(context, "armored")))
                .then(Commands.literal("molten")
                    .executes(context -> RunCommandHandlers.setRunModifier(context, "molten")))
                .then(Commands.literal("regenerative")
                    .executes(context -> RunCommandHandlers.setRunModifier(context, "regenerative")))
                .then(Commands.literal("summoner")
                    .executes(context -> RunCommandHandlers.setRunModifier(context, "summoner")))
                .then(Commands.literal("swarm")
                    .executes(context -> RunCommandHandlers.setRunModifier(context, "swarm")))
                .then(Commands.literal("none").executes(RunCommandHandlers::clearRunModifiers)))
            .then(Commands.literal("floor")
                .then(Commands.argument("number", IntegerArgumentType.integer(1))
                    .executes(RunCommandHandlers::setRunFloorNumber)))
            .then(Commands.literal("targetrooms")
                .then(Commands.argument("count", IntegerArgumentType.integer(1))
                    .executes(RunCommandHandlers::setRunTargetRoomCount)))
            .then(Commands.literal("startfloor")
                .then(Commands.argument("floor", IntegerArgumentType.integer(1))
                    .executes(RunCommandHandlers::startFloorRun)))
            .then(Commands.literal("presetstart")
                .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                    .executes(RunCommandHandlers::startPresetFloorRun)))
            .then(Commands.literal("linearstart")
                .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                    .executes(RunCommandHandlers::startPresetFloorRun))
                .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                    .then(Commands.literal("chained")
                        .executes(RunCommandHandlers::startChainedPresetFloorRun))
                    .then(Commands.literal("chained")
                        .then(Commands.argument("stepRadius", IntegerArgumentType.integer(1))
                            .executes(RunCommandHandlers::startChainedPresetFloorRun)))))
            .then(Commands.literal("linearclaimstart")
                .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                    .executes(RunCommandHandlers::startPostPlacementClaimLinearRun))
                .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                    .then(Commands.argument("stepRadius", IntegerArgumentType.integer(1))
                        .executes(RunCommandHandlers::startPostPlacementClaimLinearRun))))
            .then(Commands.literal("nextfloor").executes(RunCommandHandlers::advanceRunFloor))
            .then(Commands.literal("advancefloor").executes(RunCommandHandlers::advanceRunFloor))
            .then(Commands.literal("portal")
                .then(Commands.literal("continue").executes(RunCommandHandlers::continueRunFromPortal))
                .then(Commands.literal("returnhome").executes(RunCommandHandlers::returnHomeFromPortal)))
            .then(Commands.literal("end").executes(RunCommandHandlers::endRun))
            .then(Commands.literal("reset").executes(RunCommandHandlers::resetRun)));

        root.then(Commands.literal("hub")
            .then(Commands.literal("debug").executes(RunCommandHandlers::debugHub))
            .then(Commands.literal("setspawn").executes(RunCommandHandlers::setHubSpawn))
            .then(Commands.literal("setreturn").executes(RunCommandHandlers::setHubReturn))
            .then(Commands.literal("setgate").executes(RunCommandHandlers::setHubGate))
            .then(Commands.literal("setsafezone").executes(RunCommandHandlers::setHubSafeZone))
            .then(Commands.literal("return").executes(RunCommandHandlers::returnToHub))
            .then(Commands.literal("preparefloor")
                .then(Commands.argument("floor", IntegerArgumentType.integer(1))
                    .executes(RunCommandHandlers::prepareHubFloor)))
            .then(Commands.literal("preparepreset")
                .then(Commands.argument("rooms", IntegerArgumentType.integer(1))
                    .executes(RunCommandHandlers::prepareHubPreset)))
            .then(GeneratedLinearConnectorPlacementCommands.registerSoloTeleporterCommand())
            .then(Commands.literal("open").executes(RunCommandHandlers::openHubGate))
            .then(Commands.literal("close").executes(RunCommandHandlers::closeHubGate)));
    }
}
